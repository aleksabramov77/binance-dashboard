// Сроки, порядок и флаги фьючерсной сделки (spec 0012, PR 2c).
//
// Флаги Hedge mode — только здесь. Включены после «окна обслуживания» 2026-10-16 (решение пользователя
// 2026-10-15): на пустом демо-счёте проверено, что счёт переключается в Hedge, лонг и шорт по монете живут
// раздельно, у каждого зеркала свои стоп и тейк на свой объём, а «стоп до входа» принимается биржей до
// позиции и при его отказе вход не отправляется (журнал spec 0012).

/**
 * Общий срок одной сделки (вход + защита) при сплошных таймаутах биржи: позже новые ожидания и
 * перечитывания не начинаются, статус честный (unprotected, если позиция могла открыться). Стоп и
 * откат всё равно пробуем — позиция без стопа хуже лишних секунд. Прогон крона — до 10 входов в
 * бюджете 200 с (MIRROR.runBudgetMs), maxDuration роута — 300 с.
 */
export const TRADE_DEADLINE_MS = 60_000;

/**
 * Неизвестный исход фьючерсного входа на стороне с другими зеркалами (PR 2d): прирост стороны
 * считается своим входом, если отличается от объёма заявки не больше чем на эту долю, и «входа не
 * было», если он сам не больше её. Между — неясно, чей объём (unprotected).
 */
export const FUTURES_GROWTH_TOLERANCE = 0.01;

/**
 * Автопереключение счёта в Hedge mode (POST /fapi/v1/positionSide/dual) перед входом, если счёт в
 * One-way и пуст (нет позиций и ордеров). Нужно после «Сбросить всё Demo» и смены демо-счёта: режим
 * переключается только на пустом счёте. Выключить — режим только читается: One-way работает как
 * раньше, Hedge (если включён) — в Hedge.
 */
export const FUTURES_AUTO_HEDGE = true;

/**
 * «Стоп до входа» (AC10): в Hedge mode сначала стоп с positionSide + quantity, при его отказе вход
 * не отправляется — позиции без стопа не бывает даже на секунду. Проверено на демо в окне 2026-10-16
 * (биржа принимает стоп без позиции; отказ −2021 — входа нет). В One-way не действует.
 */
export const FUTURES_STOP_BEFORE_ENTRY = true;
