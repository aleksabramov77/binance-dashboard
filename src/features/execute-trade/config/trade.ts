// Сроки, порядок и флаги фьючерсной сделки (spec 0012, PR 2c).
//
// Флаги Hedge mode — только здесь. Включаются вместе в «окне обслуживания» (решение пользователя
// 2026-10-15): пауза крона зеркала → «Сбросить всё Demo» (пустой фьючерсный счёт) → локально
// `FUTURES_AUTO_HEDGE = true` (и при проверке AC10 `FUTURES_STOP_BEFORE_ENTRY = true`) → `pnpm wt serve`
// → вход с /signals → проверка на demo.binance.com → затем 2d и выкатка с включёнными флагами.

/**
 * Общий срок одной сделки (вход + защита) при сплошных таймаутах биржи: позже новые ожидания и
 * перечитывания не начинаются, статус честный (unprotected, если позиция могла открыться). Стоп и
 * откат всё равно пробуем — позиция без стопа хуже лишних секунд. Прогон крона — до 10 входов в
 * бюджете 200 с (MIRROR.runBudgetMs), maxDuration роута — 300 с.
 */
export const TRADE_DEADLINE_MS = 60_000;

/**
 * Автопереключение счёта в Hedge mode (POST /fapi/v1/positionSide/dual) перед входом, если счёт в
 * One-way и пуст (нет позиций и ордеров). Выключено: Hedge на демо не проверен, а счёт может
 * опустеть сам (ночью закроются все позиции) — переключать его непроверенным кодом нельзя.
 * Выключено — режим только читается: One-way работает как раньше, Hedge (если включён вручную) —
 * в Hedge.
 */
export const FUTURES_AUTO_HEDGE = false;

/**
 * «Стоп до входа» (AC10): в Hedge mode сначала стоп с positionSide + quantity, при его отказе вход
 * не отправляется. Выключено: на демо не проверено, принимает ли биржа стоп без позиции, — счёт в
 * One-way с позициями зеркала, переключить нельзя. Включать после проверки на пустом счёте.
 */
export const FUTURES_STOP_BEFORE_ENTRY = false;
